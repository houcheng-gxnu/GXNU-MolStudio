def vesta_color(z, default=(0.55, 0.55, 0.55)):
    """取某元素的 VESTA 颜色；表里没有（超重元素）时返回 default。"""
    return VESTA_COLORS.get(int(z), default)


def vesta_hex(z):
    """取某元素 VESTA 颜色的 ``"#RRGGBB"`` 写法（做图例/网页时方便）。"""
    r, g, b = vesta_color(z)
    return "#%02X%02X%02X" % (round(r * 255), round(g * 255), round(b * 255))


def vesta_overrides(elements=None):
    """返回可直接交给 ``set_element_colors()`` 的覆盖表 {Z: (r, g, b)}。

    elements: 需要哪些元素（原子序数的可迭代对象）；None = 表里全部。
              不认识的元素会被忽略，不抛异常。
    """
    if elements is None:
        return dict(VESTA_COLORS)
    out = {}
    for z in elements:
        try:
            zi = int(z)
        except (TypeError, ValueError):
            continue
        if zi in VESTA_COLORS:
            out[zi] = VESTA_COLORS[zi]
    return out


def self_check(ini_path=None):
    """把本模块的表和 VESTA 的 elements.ini 逐行对比。

    返回比对的元素个数；找不到 ini 时返回 None（静默跳过，不影响任何运行逻辑）。
    任何一行对不上就抛 AssertionError —— 这样"数据被手改过"会立刻暴露。
    """
    env = os.environ.get("VESTA_ELEMENTS_INI")
    cands = ([ini_path] if ini_path else
             ([env] if env else list(DEFAULT_INI_CANDIDATES)))
    path = next((p for p in cands if p and os.path.exists(p)), None)
    if path is None:
        return None                     # 找不到 ini 就静默跳过
    n = 0
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            parts = line.split()
            if len(parts) < 8 or parts[1] in ("D", "XX"):
                continue                    # 氘 / 占位行不参与元素表比对
            try:
                z = int(parts[0])
                rgb = (float(parts[5]), float(parts[6]), float(parts[7]))
            except ValueError:
                continue
            mine = VESTA_COLORS.get(z)
            if mine is None or any(abs(a - b) > 1e-6
                                   for a, b in zip(mine, rgb)):
                raise AssertionError(
                    "元素 %d 的配色与 elements.ini 不一致: %s vs %s"
                    % (z, mine, rgb))
            n += 1
    return n

