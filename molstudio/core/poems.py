_OFF_VALUES = ("0", "off", "false", "no")


def enabled():
    """是否启用启动诗词（``MOLSTUDIO_POEM`` 关掉时为 False）。"""
    return os.environ.get("MOLSTUDIO_POEM", "").strip().lower() not in _OFF_VALUES


def pick_poem(rng=None):
    """挑一首：``MOLSTUDIO_POEM`` 是标题子串时固定那一首，否则随机。

    任何异常都不该影响启动，故调用方（主窗口）整体 try/except。
    """
    want = os.environ.get("MOLSTUDIO_POEM", "").strip()
    if want and want.lower() not in _OFF_VALUES:
        for poem in POEMS:
            if want in poem["title"]:
                return poem
    return (rng or random).choice(POEMS)


# ── 字符边框版式 ────────────────────────────────────────────────
# 框内宽度（全角格数）。最长正文行 20 格
# （"不管风吹浪打，胜似闲庭信步，今日得宽馀。"），最长标题 17 格
# （"七绝·为李进同志题所摄庐山仙人洞照"），取 22 让左右各留一格以上。
BOX_INNER = 22

_CJK_SPACE = "\u3000"          # 全角空格：框内唯一的留白字符


def _to_fullwidth(text):
    """把 ASCII（含空格）转成全角，使框内每个字符都恰好占一格。

    只处理 ASCII：汉字、全角标点本来就占一格；``·``(U+00B7) 在中文字体下
    也是全角（与 GB2312 的 A1A4 一致），保持原样。
    """
    out = []
    for ch in text:
        code = ord(ch)
        if ch == " ":
            out.append(_CJK_SPACE)
        elif 0x21 <= code <= 0x7E:
            out.append(chr(code + 0xFEE0))
        else:
            out.append(ch)
    return "".join(out)


def _box_row(text, inner):
    """框内一行：左右用全角空格补足，内容整体居中（差一格时多补在右侧）。"""
    pad = max(0, inner - len(text))
    left = pad // 2
    return "│" + _CJK_SPACE * left + text + _CJK_SPACE * (pad - left) + "│"


def frame_poem(poem, inner=BOX_INNER):
    """把一首诗排成「字符边框 + 框内居中」，返回 ``[(类型, 文本行), ...]``。

    类型：``border``（上下框线）/ ``title`` / ``meta`` / ``blank`` / ``body``，
    供界面分别着色。每行字符数都等于 ``inner + 2``——因为框内已无 ASCII 字符、
    且整框交给中文字体渲染，一个字符就是一格，``len()`` 即格数。
    """
    rows = [("border", "┌" + "─" * inner + "┐")]
    rows.append(("title", _box_row(_to_fullwidth(poem["title"]), inner)))
    rows.append(("meta", _box_row(_to_fullwidth(f"毛泽东 · {poem['year']}"), inner)))
    rows.append(("blank", _box_row("", inner)))
    for line in poem["lines"]:
        rows.append(("blank" if not line else "body",
                     _box_row(_to_fullwidth(line), inner)))
    rows.append(("border", "└" + "─" * inner + "┘"))
    return rows
