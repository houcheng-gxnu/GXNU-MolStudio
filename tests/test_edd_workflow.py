# -*- coding: utf-8 -*-
"""Unit tests for the electron-density-difference workflow."""

import os
from types import SimpleNamespace

import pytest

from molstudio.core import edd


ATOMS = [
    (1, "O", 8, (0.0, 0.0, 0.0)),
    (2, "H", 1, (0.0, 0.0, 0.96)),
    (3, "H", 1, (0.93, 0.0, -0.24)),
    (4, "O", 8, (2.8, 0.0, 0.0)),
    (5, "H", 1, (3.7, 0.2, 0.0)),
    (6, "H", 1, (2.8, -0.9, 0.0)),
]


def test_parse_atom_indices():
    assert edd.parse_atom_indices("1-3, 7，9-10") == (1, 2, 3, 7, 9, 10)
    with pytest.raises(ValueError, match="格式无效"):
        edd.parse_atom_indices("1,abc")


def test_read_parent_charge_and_multiplicity(tmp_path):
    path = tmp_path / "parent.fchk"
    path.write_text(
        "Multiplicity                               I                3\n"
        "Number of electrons                        I                8\n",
        encoding="ascii")
    assert edd.read_charge_multiplicity(
        str(path), [(1, "O", 8, (0, 0, 0))]) == (0, 3)


def test_prepare_fragment_jobs_preserves_coordinates_and_nosymm(tmp_path):
    fragments = [
        edd.EDDFragment("water-A", (1, 2, 3), charge=0, multiplicity=1),
        edd.EDDFragment("ion-B", (4, 5, 6), charge=1, multiplicity=2),
    ]
    jobs = edd.prepare_fragment_jobs(
        ATOMS, fragments, str(tmp_path), "dimer", "B3LYP/6-311G**",
        nprocshared=4, mem="2GB")
    assert len(jobs) == 3
    assert jobs[0]["role"] == "complex"
    text_a = open(jobs[0]["gjf"], encoding="ascii").read()
    text_b = open(jobs[1]["gjf"], encoding="ascii").read()
    text_c = open(jobs[2]["gjf"], encoding="ascii").read()
    assert "#P B3LYP/6-311G** nosymm" in text_a
    assert "0 1" in text_a
    assert "1 2" in text_c
    atom_lines_a = [line.split() for line in text_a.splitlines()
                    if line.strip().startswith("O ")]
    atom_lines_b = [line.split() for line in text_b.splitlines()
                    if line.strip().startswith("O ")]
    assert atom_lines_a == [
        ["O", "0.0000000000", "0.0000000000", "0.0000000000"],
        ["O", "2.8000000000", "0.0000000000", "0.0000000000"],
    ]
    assert atom_lines_b == [["O", "0.0000000000", "0.0000000000",
                             "0.0000000000"]]


def test_fragment_validation_rejects_overlap_and_unassigned_atoms():
    overlap = [
        edd.EDDFragment("A", (1, 2, 3, 4)),
        edd.EDDFragment("B", (4, 5, 6)),
    ]
    with pytest.raises(edd.EDDWorkflowError, match="同时属于"):
        edd.validate_fragments(ATOMS, overlap)
    missing = [
        edd.EDDFragment("A", (1, 2, 3)),
        edd.EDDFragment("B", (4, 5)),
    ]
    with pytest.raises(edd.EDDWorkflowError, match="未分配"):
        edd.validate_fragments(ATOMS, missing)


def test_difference_sequence_uses_custom_grid_operation():
    sequence = edd.build_difference_sequence(
        ["water1.fchk", "water2.fchk"], grid_quality=2)
    assert sequence.startswith("\n5\n0\n2\n")
    assert "-,water1.fchk\n-,water2.fchk\n1\n2\n2\n0\nq\n" in sequence


def test_generate_difference_cube_copies_multiwfn_cube(
        tmp_path, monkeypatch):
    complex_fch = tmp_path / "complex.fchk"
    ref_fch = tmp_path / "ref.fch"
    complex_fch.write_text("placeholder", encoding="ascii")
    ref_fch.write_text("placeholder", encoding="ascii")
    multiwfn = tmp_path / "Multiwfn.exe"
    multiwfn.write_bytes(b"placeholder")

    def fake_run(_exe, _input_file, sequence, workdir, on_log=None,
                 cancel=None, timeout=0):
        assert "-,ref_001.fch\n" in sequence
        with open(os.path.join(workdir, "density.cub"), "w",
                  encoding="ascii") as handle:
            handle.write(
                " Generated by Multiwfn\n"
                " Totally       120 grid points\n"
                "    2    0 0 0\n"
                "   10  1 0 0\n"
                "   12  0 1 0\n"
                "    1  0 0 1\n"
                "    8  6 0 0 0\n"
                "    1  1 1 0 0\n")
        return (
            "The minimum is -1.0E-03\n"
            "The maximum is  2.0E-03\n"
            "Summing up all value and multiply differential element:\n"
            " 1.0E-10\n")

    monkeypatch.setattr(edd, "_run_multiwfn", fake_run)
    result = edd.generate_difference_cube(
        str(complex_fch), [str(ref_fch)], str(tmp_path / "out"),
        multiwfn_exe=str(multiwfn), grid_quality=2)
    assert os.path.isfile(result.cube_path)
    assert result.counts["references"] == 1
    assert result.counts["cube_points"] == 120
    assert result.stats["minimum"] == pytest.approx(-1e-3)
    assert result.stats["maximum"] == pytest.approx(2e-3)


def test_real_multiwfn_complex_minus_two_fragment_cube(tmp_path):
    multiwfn = r"E:\Multiwfn_2026.4.10_bin_Win64\Multiwfn.exe"
    base = r"E:\Multiwfn_2026.4.10_bin_Win64\examples\CDA\COBH3"
    inputs = [
        os.path.join(base, "COBH3.fch"),
        os.path.join(base, "CO.fch"),
        os.path.join(base, "BH3.fch"),
    ]
    if not os.path.isfile(multiwfn) or not all(
            os.path.isfile(path) for path in inputs):
        pytest.skip("Local Multiwfn COBH3 acceptance data unavailable")
    result = edd.generate_difference_cube(
        inputs[0], inputs[1:], str(tmp_path),
        multiwfn_exe=multiwfn, grid_quality=1)
    assert os.path.getsize(result.cube_path) > 100000
    assert result.counts["references"] == 2
    assert result.counts["cube_points"] > 10000
    assert result.stats["maximum"] > 0
    assert result.stats["minimum"] < 0
    assert abs(result.stats["integral"]) < 0.01


def test_run_fragment_jobs_chains_all_fragments_and_formchk(
        tmp_path, monkeypatch):
    fragments = [
        edd.EDDFragment("A", (1, 2, 3)),
        edd.EDDFragment("B", (4, 5)),
        edd.EDDFragment("C", (6,)),
    ]
    jobs = edd.prepare_fragment_jobs(
        ATOMS, fragments, str(tmp_path), "water", "HF/STO-3G",
        require_complete=True)
    gaussian = tmp_path / "g16.exe"
    gaussian.write_bytes(b"placeholder")
    runs = []

    def fake_run(gjf, _exe, log_path=None, on_line=None, cancel=None):
        runs.append(os.path.basename(gjf))
        if on_line:
            on_line("Gaussian output")
        with open(log_path, "w", encoding="utf-8") as handle:
            handle.write("Normal termination\n")
        chk = os.path.splitext(gjf)[0] + ".chk"
        with open(chk, "w", encoding="ascii") as handle:
            handle.write("checkpoint")
        return SimpleNamespace(
            ok=True, cancelled=False, error="", log_path=log_path)

    def fake_chk_to_fchk(chk, _converter, output_path=None):
        with open(output_path, "w", encoding="ascii") as handle:
            handle.write("formatted checkpoint")
        return output_path

    monkeypatch.setattr(edd, "run_gaussian", fake_run)
    monkeypatch.setattr(
        edd, "find_chk_file",
        lambda log_path: os.path.splitext(log_path)[0] + ".chk")
    monkeypatch.setattr(edd, "chk_to_fchk", fake_chk_to_fchk)
    progress = []
    result = edd.run_fragment_jobs(
        jobs, str(gaussian), formchk_exe=str(gaussian),
        on_progress=lambda done, total, label:
        progress.append((done, total, label)))
    assert len(runs) == 4
    assert progress[-1] == (4, 4, "C")
    assert result["complex"] == jobs[0]["fch"]
    assert [os.path.basename(path) for path in result["fragments"]] == [
        os.path.basename(job["fch"]) for job in jobs[1:]]
    assert all(os.path.isfile(path) for path in result["fragments"])
